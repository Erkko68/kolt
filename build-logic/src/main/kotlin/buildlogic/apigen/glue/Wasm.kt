package buildlogic.apigen.glue

import buildlogic.apigen.c.Abi
import buildlogic.apigen.c.CFunction

/** Writes what a wasm runtime's build and scripts take of its exports. */
internal object Wasm {
    /** The runtime's `-sEXPORTED_FUNCTIONS` file: every external's `_symbol`, plus the allocator. */
    fun exports(functions: List<CFunction>): String =
        (functions.map { "_${it.name}" } + "_malloc" + "_free").joinToString("\n", postfix = "\n")

    /**
     * The `--post-js` tables (`<prefix>BoolExports`, …) the runtime's globals script reads to adapt exports for the js
     * target: which return a C bool (wasm hands back 0/1), which return a float (js keeps it as a double), and which
     * take a 64-bit int (js passes a Kotlin Long object, wasm wants a BigInt).
     */
    fun types(functions: List<CFunction>, prefix: String): String {
        val p = prefix.lowercase()
        fun table(name: String, filter: (CFunction) -> Boolean) =
            "Module['$name'] = [${functions.filter(filter).joinToString(",") { "'${it.name}'" }}];\n"
        return table("${p}BoolExports") { it.returns == Abi.BOOL } +
            table("${p}F32Exports") { it.returns == Abi.F32 } +
            table("${p}I64Exports") { fn -> fn.params.any { it.second == Abi.I64 } }
    }

    /**
     * `WASM_ARITIES` (export → parameter count) in [pkg], for the web export parity test: a Kotlin declaration whose
     * arity differs from the compiled C function has drifted from the header.
     */
    fun arities(functions: List<CFunction>, pkg: String): String = buildString {
        append("// Generated by GenerateBindings. Do not edit.\npackage $pkg\n\n")
        append("val WASM_ARITIES: List<Pair<String, Int>> = listOf(\n")
        functions.forEach { append("    \"_${it.name}\" to ${it.params.size},\n") }
        append(")\n")
    }
}

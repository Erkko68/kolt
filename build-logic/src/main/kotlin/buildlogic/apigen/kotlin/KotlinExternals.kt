package buildlogic.apigen.kotlin

import buildlogic.apigen.ApiGenConfig
import buildlogic.apigen.Layout
import buildlogic.apigen.c.Abi
import buildlogic.apigen.c.CFunction
import buildlogic.apigen.c.CManifest
import java.io.File

/**
 * The Kotlin externals of each header in [manifest], by path under the Kotlin dir: in its package
 * ([Layout.externalsPackage]), in the Kotlin module named as its C module.
 */
internal fun kotlinExternals(manifest: CManifest, config: ApiGenConfig, layout: Layout): Map<String, String> =
    manifest.headers.entries.associate { (header, functions) ->
        val pkg = layout.externalsPackage(header)
        "${layout.sourceDir(header.substringBefore('/'), pkg)}/${File(header).nameWithoutExtension}.kt" to
            KotlinExternalsWriter.write(header, functions, pkg, config.kotlin!!.interop)
    }

/**
 * Writes the common `@ExternalSymbolName external fun` of a C header's functions, named like the C symbol (web binds
 * by global name), with the types externals take ([Abi.kotlin]): any pointer is a `NativePointer`, 32-bit integers
 * and enums an `Int`, 64-bit ones a `Long`.
 */
internal object KotlinExternalsWriter {
    /** The Kotlin file binding [functions] (of the header `c/[source]`) in [pkg]; [interop]: the package declaring the two names. */
    fun write(source: String, functions: List<CFunction>, pkg: String, interop: String) =
        "// Generated by generateKotlinExternals from c/$source; do not edit.\n" +
            "package $pkg\n\nimport $interop.ExternalSymbolName\n" +
            (if (functions.any { f -> f.returns == Abi.PTR || f.params.any { it.second == Abi.PTR } }) "import $interop.NativePointer\n" else "") +
            functions.joinToString("") { "\n${external(it)}" }

    private fun external(f: CFunction): String {
        val params = f.params.joinToString { (name, abi) -> "${if (name in KEYWORDS) "`$name`" else name}: ${abi.kotlin}" }
        val result = f.returns.kotlin?.let { ": $it" }.orEmpty()
        return "@ExternalSymbolName(\"${f.name}\")\ninternal external fun ${f.name}($params)$result\n"
    }

    val KEYWORDS = setOf(
        "as", "break", "class", "continue", "do", "else", "false", "for", "fun", "if", "in", "interface", "is", "null",
        "object", "package", "return", "super", "this", "throw", "true", "try", "typealias", "typeof", "val", "var",
        "when", "while",
    )
}

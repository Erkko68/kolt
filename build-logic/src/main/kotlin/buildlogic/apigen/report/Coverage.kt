package buildlogic.apigen.report

import buildlogic.apigen.c.Binding
import buildlogic.apigen.c.Bound.Role
import buildlogic.apigen.c.CApi

/** `api-coverage.txt`'s [text], and the counts it opens with. */
internal class Coverage(val text: String, val summary: String)

/**
 * Each C function the C++ API calls for: bound, and a public Kotlin wrapper calls it (`wrapped`) or none does yet
 * (`unwrapped`); or why it isn't bound (`todo`, `skipped`). An upcast the class inherits through another counts as
 * wrapped. Then each enum value and class constant of that API, which no function carries: the Kotlin API declares it
 * (`declared`) or doesn't (`undeclared`; `untyped` when it has no declaration of the owner's name).
 *
 * [kotlinSources]: the Kotlin API's ([kotlinApiSources]), generated and hand-written alike. Without them, for a C API
 * alone, a C function is just `bound`, and the values are left out.
 */
internal fun coverage(c: CApi, headers: Set<String>, prefix: String, kotlinSources: String?): Coverage {
    fun lines(status: (Binding) -> String) = c.bindings.distinctBy { it.c to it.cpp }.sortedWith(compareBy({ it.c }, { it.cpp })).map { b ->
        "${(b.gap?.kind?.name?.lowercase() ?: status(b)).padEnd(9)} ${b.c} = ${b.cpp}" + (b.gap?.let { "  -- ${it.reason}" } ?: "")
    }
    if (kotlinSources == null) {
        val lines = lines { "bound" }
        val summary = summary(lines, C_STATUSES)
        return Coverage(
            "# Generated by apiCoverage; do not edit. Each C function the C++ API calls for: bound, or why it isn't (todo, skipped).\n" +
                "# $summary\n\n" + lines.joinToString("\n", postfix = "\n"),
            summary,
        )
    }
    val called = Regex("""\b${Regex.escape(prefix)}\w+""").findAll(kotlinSources).mapTo(HashSet()) { it.value }
    // An upcast the API doesn't call is wrapped when the ones it calls lead to the same base: the class inherits it.
    // So is a constructor without arguments, when the class is created as one a subclass overrides.
    val names = c.names
    val upcasts = c.bindings.filter { it.bound?.role == Role.UPCAST && it.c in called }.groupBy({ names.type(it.bound!!.owner) }) { it.bound!!.name }
    fun reaches(from: String, base: String): Boolean = upcasts[from].orEmpty().any { it == base || reaches(it, base) }
    val lines = lines { b ->
        val bound = b.bound
        val inherited = bound != null && when (bound.role) {
            Role.UPCAST -> reaches(names.type(bound.owner), bound.name)
            Role.CREATE -> bound.params.isEmpty() && "${names.type(bound.owner)}_createUpcalls" in called
            else -> false
        }
        if (b.c in called || inherited) "wrapped" else "unwrapped"
    }
    val summary = summary(lines, STATUSES)
    val api = c.api
    val declarations = KotlinDeclarations(kotlinSources)
    val values = (api.apiEnums(headers).flatMap { e ->
        // Kotlin names an enum as the API's alias does.
        val scope = declarations.scope(api.aliasesOf(e.name)) ?: return@flatMap listOf("untyped" to e.name)
        e.constants.map { "${e.name}::${it.first}" }.filter { api.skipReason(it) == null }.map { declarations.status(scope, it) to it }
    } + api.apiConstants(headers).map { constant ->
        (declarations.scope(listOf(constant.substringBeforeLast("::")))?.let { declarations.status(it, constant) } ?: "untyped") to constant
    }).map { (status, name) -> "${status.padEnd(10)} $name" }
    val valueSummary = summary(values, VALUE_STATUSES)
    return Coverage(
        "# Generated by apiCoverage; do not edit. Each C function the C++ API calls for: bound, and a public Kotlin wrapper\n" +
            "# calls it (wrapped) or none does yet (unwrapped); or why it isn't bound (todo, skipped).\n# $summary\n\n" + lines.joinToString("\n", postfix = "\n") +
            "\n# Each enum value and class constant of that API: the Kotlin API declares it (declared) or doesn't (undeclared);\n" +
            "# untyped: Kotlin has no declaration of the enum's, or the constant's owner's, name.\n# $valueSummary\n\n" + values.joinToString("\n", postfix = "\n"),
        "$summary; $valueSummary",
    )
}

private fun summary(lines: List<String>, statuses: List<String>) =
    lines.groupingBy { it.substringBefore(' ') }.eachCount().let { counts -> statuses.joinToString(", ") { "${counts[it] ?: 0} $it" } }

private val STATUSES = listOf("wrapped", "unwrapped", "todo", "skipped")
private val C_STATUSES = listOf("bound", "todo", "skipped")
private val VALUE_STATUSES = listOf("declared", "undeclared", "untyped")
